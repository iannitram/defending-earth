"""Turn clear_states.json (measured from Blender's atmosphere renders) into
assets/sky/looks.txt, the table the game reads. Run: python3 make_looks.py
Units: scaled so the noon sun is 11.0 in green, white-balanced to the noon sun
(a camera set to daylight)."""
import json, math, os
here = os.path.dirname(os.path.abspath(__file__))
res = json.load(open(os.path.join(here, "clear_states.json")))
DISC = (8.0 / 0.545) ** 2          # the sun was rendered as an 8 degree disc; same energy
sun = lambda r: [c * DISC / math.pi for c in r["sun_irr_normal"]]
n = sun(res["noon"])
wb = [n[0] / n[1], 1.0, n[2] / n[1]]
k = 11.0 / n[1]
order = ["dawn", "morning", "noon", "afternoon", "golden", "dusk"]
lines = ["# state  sun rgb  zenith rgb  horizon rgb  glow rgb   (linear, white-balanced; generated by source_assets/blender/sky/make_looks.py)"]
for name in order:
    r = res[name]
    f = lambda v: [max(c, 0.0) * k / w for c, w in zip(v, wb)]
    glow = [g - h for g, h in zip(r["glow"], r["horizon"])]
    s = sun(r)
    if r["el"] <= 0:               # sun below the horizon: the bright band of sky does the lighting
        s = [g * 0.35 for g in glow]
    vals = f(s) + f(r["zenith"]) + f(r["horizon"]) + f(glow)
    lines.append(name + " " + " ".join("%.4f" % v for v in vals))
open(os.path.join(here, "../../../assets/sky/looks.txt"), "w").write("\n".join(lines) + "\n")
print("\n".join(lines))
